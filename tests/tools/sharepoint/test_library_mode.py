class FakeResponse:
    def __init__(self, status: int, body=None, headers: Optional[Dict[str, str]] = None, raw: bytes = None):
        self.status_code = status
        self.headers = headers or {}
        self._raw = raw if raw is not None else json.dumps(body if body is not None else {}).encode()

    def iter_content(self, chunk_size=1):
        for i in range(0, len(self._raw), chunk_size):
            yield self._raw[i:i + chunk_size]

    def close(self):
        pass


def item(item_id, path, **fields):
    leaf = path.rsplit("/", 1)[-1]
    return {"id": str(item_id), "webUrl": f"https://{HOST}{path}",
            "fields": {"FileLeafRef": leaf, "ContentType": "Document", "_UIVersionString": "1.0",
                       "AuthorLookupId": "7", **fields}}


def doc_fields(doc_id, category, owner="Head of Unit"):
    return {
        "HBDocumentID_x0020_": doc_id,
        "Document_x0020_Owner_x0020__x0028_position_x0029_": owner,
        "LastApproverName": SECRET_VALUE,
        "LastApprovalDate": "2026-01-15T00:00:00Z",
        "TopicArea": "Operations",
        "RegionCountry": "Global",
        "DocCategory": category,
    }


class FakeGraph:
    """Routes GET requests by path; records every call."""

    def __init__(self, lists: Dict[str, List[dict]], page_size: int = 1000, catalogue: List[dict] = None):
        self.lists = lists
        self.page_size = page_size
        self.catalogue = catalogue if catalogue is not None else [
            {"id": list_id, "displayName": name, "name": name.replace(" ", "")}
            for name, list_id in ((LIB, LIB_ID), ("Archive Library", "list-0002")) if list_id in lists]
        self.calls: List[dict] = []
        self.scripted: List[FakeResponse] = []   # returned before routing, one per call

    def get(self, url, params=None, timeout=None, allow_redirects=True, stream=False, headers=None):
        self.calls.append({"url": url, "params": params, "timeout": timeout,
                           "allow_redirects": allow_redirects, "headers": headers})
        if self.scripted:
            return self.scripted.pop(0)
        parts = urlsplit(url)
        assert parts.hostname == lm.GRAPH_HOST
        path = unquote(parts.path)
        if path == f"/v1.0/sites/{HOST}:/sites/handbook":
            return FakeResponse(200, {"id": "site,1,2"})
        if path == "/v1.0/sites/site,1,2/lists":
            return FakeResponse(200, {"value": self.catalogue})
        prefix = "/v1.0/sites/site,1,2/lists/"
        if path.startswith(prefix) and path.endswith("/items"):
            list_id = path[len(prefix):-len("/items")]
            rows = self.lists[list_id]
            start = int(dict(p.split("=") for p in parts.query.split("&") if p).get("skip", 0)) if parts.query else 0
            page = rows[start:start + self.page_size]
            body = {"value": page}
            if start + self.page_size < len(rows):
                body["@odata.nextLink"] = f"https://{lm.GRAPH_HOST}{parts.path}?skip={start + self.page_size}"
            return FakeResponse(200, body)
        return FakeResponse(404, {"error": {"code": "itemNotFound"}})


def client(graph: FakeGraph, sleeps=None):
    return lm.GraphListClient(SITE, get_token=lambda: "tok", session=graph,
                              sleep=(sleeps.append if sleeps is not None else (lambda s: None)))


def settings(**kwargs):
    kwargs.setdefault("library_lists", [LIB])
    return lm.LibrarySettings.from_settings(**kwargs)


def graph_file(path, name=None):
    """A file as the Graph backend's get_files_list returns it."""
    name = name or path.rsplit("/", 1)[-1]
    return {"Name": name, "Path": f"/drives/b!x/root:/{name}", "Created": "2026-01-01T00:00:00Z",
            "Modified": "2026-02-01T00:00:00Z", "Link": f"https://{HOST}{path.replace(' ', '%20')}", "id": f"id-{name}"}


def rest_file(path):
    """A file as the REST backend returns it: server-relative path, sometimes no link."""
    return {"Name": path.rsplit("/", 1)[-1], "Path": path, "Created": "c", "Modified": "m", "Link": "", "id": "u"}


P1 = "/sites/handbook/Handbook Library/Travel Rules.pdf"
P2 = "/sites/handbook/Handbook Library/sub/Leave Policy.pdf"
P3 = "/sites/handbook/Handbook Library/Remote Work.docx"


def standard_lists():
    return {LIB_ID: [
        item(1, P1, **doc_fields("HB-001", "Travel")),
        item(2, P2, **doc_fields("HB-002", "People")),
        item(3, P3, **doc_fields("HB-003", ["People", "Remote"])),
    ]}


def join(files, graph=None, **setting_kwargs):
    graph = graph or FakeGraph(standard_lists())
    s = settings(**setting_kwargs)
    index = lm.build_index(client(graph), s)
    counts = lm.JoinCounts()
    kept = []
    for f in files:
        meta = dict(f)
        if lm.apply_library_metadata(meta, index, s, counts):
            kept.append(meta)
    return kept, counts, graph


