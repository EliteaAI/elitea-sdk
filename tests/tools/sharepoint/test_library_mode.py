def test_connection_errors_are_retried_then_typed():
    import requests

    class Flaky(FakeGraph):
        def __init__(self):
            super().__init__({})
            self.failures = 2

        def get(self, url, **kwargs):
            if self.failures:
                self.failures -= 1
                raise requests.ConnectionError("down")
            return super().get(url, **kwargs)

    assert client(Flaky()).site_id() == "site,1,2"

    class Down(FakeGraph):
        def get(self, url, **kwargs):
            raise requests.Timeout("slow")

    with pytest.raises(lm.LibraryMetadataError, match="did not answer"):
        client(Down({})).site_id()


